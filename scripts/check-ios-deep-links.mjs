import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import ts from "typescript";
const source = ts.createSourceFile("AppNavigator.tsx", readFileSync("apps/mobile/src/navigation/AppNavigator.tsx", "utf8"), ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX);
let callback;
function visit(node) {
  if (ts.isCallExpression(node) && node.expression.getText(source) === "useEffect" && node.arguments[0]?.getText(source).includes("Linking.getInitialURL")) callback = node.arguments[0].getText(source);
  ts.forEachChild(node, visit);
}
visit(source);
assert.ok(callback, "production link effect must exist");
const run = new Function("Linking", "appState", "handledDeepLinkRef", ts.transpileModule(`const effect = ${callback};`, {}).outputText + "\nreturn effect();");
const url = "weatheron://destination?id=synthetic-destination";
const routes = [];
let listener;
const linking = { getInitialURL: async () => url, addEventListener: (_, callback) => { listener = callback; return { remove() {} }; } };
const state = { destinationSelectionReady: true, savedDestinations: [{ place: { id: "synthetic-destination" } }], navigate: (route) => routes.push(route), selectDestinationPlace: () => {} };
const handled = { current: null };
let dispose = run(linking, state, handled);
await Promise.resolve();
assert.deepEqual(routes, ["G2"]);
dispose();
dispose = run(linking, state, handled);
await Promise.resolve();
assert.deepEqual(routes, ["G2"], "rerender must not replay the launch URL");
listener({ url });
assert.deepEqual(routes, ["G2", "G2"], "a second Live Activity/widget tap on the same URL must navigate again");
listener({ url });
assert.equal(routes.length, 3);
assert.doesNotThrow(() => listener({ url: "weatheron://destination?id=%ZZ" }));
assert.equal(routes.length, 3, "malformed external URL must be ignored");
dispose();
const pending = { current: null };
state.destinationSelectionReady = false;
dispose = run(linking, state, pending);
await Promise.resolve();
assert.equal(pending.current, null);
dispose();
state.destinationSelectionReady = true;
dispose = run(linking, state, pending);
await Promise.resolve();
assert.equal(routes.at(-1), "G2");
dispose();
let resolveInitial;
const deferred = { ...linking, getInitialURL: () => new Promise((resolve) => { resolveInitial = resolve; }) };
const count = routes.length;
const cleanup = run(deferred, state, { current: null });
cleanup();
resolveInitial(url);
await Promise.resolve();
assert.equal(routes.length, count, "an unmounted effect must not process a late initial URL");
console.log("iOS deep links: cold restore, repeated warm taps, malformed URL and cancelled effect passed");
